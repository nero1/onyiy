import fs from 'node:fs';
import path from 'node:path';
import {initialSchemaFile,migrationSource} from '../packages/db/src/migration-source';
const dir=path.join(process.cwd(),'packages/db/src/migrations');
const files=fs.readdirSync(dir).filter(name=>name.endsWith('.sql')).sort();
if(files.length!==1||files[0]!==initialSchemaFile)throw new Error('ONE_FINAL_STATE_MIGRATION_REQUIRED');
const source=fs.readFileSync(path.join(dir,initialSchemaFile),'utf8');
const migration=migrationSource(initialSchemaFile,source);
const receipts=[...source.matchAll(/INSERT INTO public\.schema_migrations\(name,sha256\) VALUES\('([^']+)','([a-f0-9]{32})'\|\|'([a-f0-9]{32})'\);/g)];
if(receipts.length!==1||receipts[0][1]!==initialSchemaFile||receipts[0][2]+receipts[0][3]!==migration.sha256)throw new Error('INITIAL_SCHEMA_RECEIPT_INVALID');
if(!source.startsWith('-- Gifters World: final-state schema')||!source.includes('INITIAL_SCHEMA_REQUIRES_EMPTY_DATABASE')||/ALTER TABLE public\.[a-z_]+ ADD COLUMN/i.test(source))throw new Error('FINAL_STATE_MIGRATION_INVALID');
if(fs.existsSync(path.join(process.cwd(),'packages/db/fresh-install.sql')))throw new Error('DUPLICATE_SCHEMA_INSTALLER');
console.log('One final-state migration, self-checksum and standalone/CLI receipt verified.');
